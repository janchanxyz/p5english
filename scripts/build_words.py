def normalize_word(w: str) -> str:
    w = w.strip().lower()
    w = w.replace("-", "").replace(" ", "")
    return "".join(c for c in w if "a" <= c <= "z")

def main():
    seen = set()
    items = []
    for word, zh, pos, theme in RAW:
        w = normalize_word(word)
        if not w or w in seen:
            continue
        if len(w) < 5 or len(w) > 14:
            continue
        seen.add(w)
        items.append({
            "id": w,
            "word": w,
            "zh": zh,
            "pos": pos,
            "theme": theme,
            "imageUrl": "",
            "imageCredit": "",
            "imageUrls": [],
        })
    items.sort(key=lambda x: x["word"])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(items, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(items)} words → {OUT}")
    from collections import Counter
    print("len dist", dict(sorted(Counter(len(i['word']) for i in items).items())))
    print("themes", dict(sorted(Counter(i['theme'] for i in items).items())))

if __name__ == "__main__":
    main()
