# Fallbacks by POS if not in HAND — must include {w}
TEMPLATES = {
  "n": [
    ("The {w} is important in our daily life.", "呢個{zh}喺日常生活好重要。"),
    ("I learned a new fact about the {w}.", "我學到關於{zh}嘅新知識。"),
  ],
  "v": [
    ("We {w} carefully in class.", "我哋喺堂上小心咁{zh}。"),
    ("Students {w} every day to improve.", "學生每日{zh}嚟進步。"),
  ],
  "adj": [
    ("The view looks {w} from the Peak.", "喺山頂睇落景色好{zh}。"),
    ("She felt {w} after the good news.", "聽到好消息之後佢感到{zh}。"),
  ],
}

def ensure_word_in_example(example: str, word: str) -> str:
    if re.search(rf"\b{re.escape(word)}\b", example, flags=re.I):
        return example
    # force insert at end as last resort
    return f"I can spell the word {word}."

def grammar_touchups(example: str, word: str, pos: str) -> str:
    e = example.strip()
    # British spelling preferences used in HK schools
    e = e.replace("colorful", "colourful").replace("favorite", "favourite")
    e = e.replace("organize", "organise").replace("recognize", "recognise")
    # Fix common a/an before word if template used "a {w}" wrongly — handled in HAND mostly
    # Capitalize first letter
    if e and e[0].islower():
        e = e[0].upper() + e[1:]
    if not e.endswith(('.', '!', '?')):
        e += '.'
    return ensure_word_in_example(e, word)

def main():
    items = json.loads(DATA.read_text(encoding="utf-8"))
    p4_by = {}
    if P4.exists():
        for x in json.loads(P4.read_text(encoding="utf-8")):
            p4_by[x["word"]] = x

    fixed = 0
    from_p4_ex = 0
    from_hand = 0
    from_tmpl = 0
    imgs = 0

    for it in items:
        w = it["word"]
        pos = it.get("pos") or "n"
        zh = it.get("zh") or w

        # images from P4 overlap
        if w in p4_by:
            src = p4_by[w]
            for k in ("imageUrl", "imageCredit", "imageUrls", "imageCredits", "thumbUrl"):
                if src.get(k) and not it.get(k):
                    it[k] = src[k]
                    imgs += 1

        # examples: prefer HAND, else reuse good P4, else template
        if w in HAND:
            ex, exzh = HAND[w]
            from_hand += 1
        elif w in p4_by and p4_by[w].get("example"):
            ex = p4_by[w]["example"]
            exzh = p4_by[w].get("exampleZh") or ""
            from_p4_ex += 1
        else:
            opts = TEMPLATES.get(pos, TEMPLATES["n"])
            # pick stable template by word hash
            t_en, t_zh = opts[sum(ord(c) for c in w) % len(opts)]
            ex = t_en.format(w=w)
            exzh = t_zh.format(zh=zh)
            from_tmpl += 1

        before = it.get("example")
        ex2 = grammar_touchups(ex, w, pos)
        it["example"] = ex2
        it["exampleZh"] = exzh
        if before and before != ex2:
            fixed += 1

        # Extra grammar fixes for known P4 issues that may have been reused
        # basketball/baseball "kick" -> play
        if w == "basketball" and "kick" in it["example"].lower():
            it["example"] = "We play basketball in the park."
            it["exampleZh"] = "我哋喺公園打籃球。"
            fixed += 1
        if w == "baseball" and "kick" in it["example"].lower():
            it["example"] = "The team plays baseball on Sunday."
            it["exampleZh"] = "球隊星期日打棒球。"
            fixed += 1

    # Second pass: automated grammar checks / fixes
    grammar_fixes = []
    for it in items:
        w = it["word"]
        ex = it["example"]
        orig = ex
        # missing article before countable singular nouns in "I like to eat X" patterns already hand-fixed
        # a/an before word when "a {vowel...}"
        ex = re.sub(r"\ba ([aeiouAEIOU]\w*)\b", r"an \1", ex)
        # an before consonant sound starting with consonant letter (rough)
        ex = re.sub(r"\ban ([bcdfghjklmnpqrstvwxyzBCDFGHJKLMNPQRSTVWXYZ]\w*)\b", r"a \1", ex)
        # ensure word present
        if not re.search(rf"\b{re.escape(w)}\b", ex, flags=re.I):
            ex = f"Today we learned the word {w}."
            it["exampleZh"] = f"今日我哋學咗「{it['zh']}」呢個字。"
        if ex != orig:
            grammar_fixes.append((w, orig, ex))
            it["example"] = ex

    DATA.write_text(json.dumps(items, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    with_img = sum(1 for x in items if x.get("imageUrl"))
    with_ex = sum(1 for x in items if x.get("example") and x.get("exampleZh"))
    print(f"words={len(items)} examples={with_ex} images={with_img}")
    print(f"from_hand={from_hand} from_p4={from_p4_ex} from_tmpl={from_tmpl} img_fields_copied≈{imgs}")
    print(f"auto_grammar_fixes={len(grammar_fixes)}")
    for w, a, b in grammar_fixes[:20]:
        print(f"  FIX {w}: {a!r} -> {b!r}")

if __name__ == "__main__":
    main()
